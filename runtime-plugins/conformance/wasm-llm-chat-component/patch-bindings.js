#!/usr/bin/env bun
// ABOUTME: Re-apply the sanctioned wit-bindgen export-shim fix to freshly generated chat bindings.
// ABOUTME: Byte-compares the patched output with the committed `src/generated.rs`; drift fails.
const fs = require("fs");
const path = require("path");

const crateDir = path.resolve(process.argv[2] ?? __dirname);
const freshPath = path.join(crateDir, "src", "bindings.rs");
const committedPath = path.join(crateDir, "src", "generated.rs");
const write = process.argv.includes("--write");

const HEADER = `// ABOUTME: Committed conformance llm-chat-world bindings with ONE sanctioned wit-bindgen fix:
// ABOUTME: E0506 list<borrow<blob-handle>> export-shim lift; plugin:build-conformance byte-compares on rebuild.
`;

const IMAGES_LOOP_OLD = [
  "                    let mut result12 = _rt::Vec::with_capacity(len12);",
  "                    for i in 0..len12 {",
  "                        let base = base12.add(i * 4);",
  "                        let e12 = {",
  "                            let l10 = *base.add(0).cast::<i32>();",
  "                            {",
  "                                handle11 = unsafe {",
  "                                    super::super::super::super::langnext::runtime_plugin::common::BlobHandle::from_handle(",
  "                                        l10 as u32,",
  "                                    )",
  "                                };",
  "                                &handle11",
  "                            }",
  "                        };",
  "                        result12.push(e12);",
  "                    }",
].join("\n");

const IMAGES_LOOP_NEW = [
  "                    // Sanctioned fix: lift each borrowed blob handle into an owned vec first,",
  "                    // then borrow the owned handles after the loop (wit-bindgen hoists a single",
  "                    // temp `let handleN;` that is E0506 under NLL for list<borrow<resource>>).",
  "                    let mut handle_vec12 = _rt::Vec::with_capacity(len12);",
  "                    for i in 0..len12 {",
  "                        let base = base12.add(i * 4);",
  "                        let l10 = *base.add(0).cast::<i32>();",
  "                        handle_vec12.push(unsafe {",
  "                            super::super::super::super::langnext::runtime_plugin::common::BlobHandle::from_handle(",
  "                                l10 as u32,",
  "                            )",
  "                        });",
  "                    }",
  "                    let mut result12 = _rt::Vec::with_capacity(len12);",
  "                    for handle11 in handle_vec12.iter() {",
  "                        result12.push(handle11);",
  "                    }",
].join("\n");

function applyOnce(content, needle, replacement, label) {
  const index = content.indexOf(needle);
  if (index === -1) {
    console.error(`error: patch-bindings: ${label} pattern not found in freshly generated bindings`);
    process.exit(1);
  }
  return content.slice(0, index) + replacement + content.slice(index + needle.length);
}

let content = fs.readFileSync(freshPath, "utf8");

// 1. Sanctioned header after the generator banner.
content = applyOnce(
  content,
  "// Generated by `wit-bindgen` 0.41.0. DO NOT EDIT!\n",
  "// Generated by `wit-bindgen` 0.41.0. DO NOT EDIT!\n" + HEADER,
  "header",
);

// 2. cfg(feature = "std")-gate the three std::error::Error impls (macro `std_feature` behavior).
for (const name of ["PluginError", "ResourceError", "BrokerError"]) {
  const needle = `            impl std::error::Error for ${name} {}\n`;
  content = applyOnce(content, needle, `            #[cfg(feature = "std")]\n` + needle, `std-error-impl ${name}`);
}

// 3. Drop the hoisted single temp declaration.
content = applyOnce(content, "                    let handle11;\n", "", "hoisted-handle11-decl");

// 4. Rewrite the images lift loop (owned vec then borrow pass).
content = applyOnce(content, IMAGES_LOOP_OLD, IMAGES_LOOP_NEW, "images-lift-loop");

if (write) {
  fs.writeFileSync(committedPath, content);
  console.log("ok: wrote patched chat bindings to src/generated.rs");
  process.exit(0);
}

// The patched output must byte-match the committed bindings.
const committed = fs.readFileSync(committedPath, "utf8");
if (content !== committed) {
  console.error("error: patch-bindings: patched fresh bindings differ from committed src/generated.rs");
  const fresh = content.split("\n");
  const old = committed.split("\n");
  for (let i = 0; i < Math.max(fresh.length, old.length); i++) {
    if (fresh[i] !== old[i]) {
      console.error(`  first diff at line ${i + 1}`);
      console.error(`  fresh:   ${JSON.stringify(fresh[i])}`);
      console.error(`  committed: ${JSON.stringify(old[i])}`);
      break;
    }
  }
  process.exit(1);
}
console.log("ok: chat bindings regeneration + sanctioned patch byte-matches committed src/generated.rs");
